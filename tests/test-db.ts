import { PGlite } from "@electric-sql/pglite";
import { drizzle } from "drizzle-orm/pglite";
import { migrate } from "drizzle-orm/pglite/migrator";
import * as schema from "@/server/db/schema";
import type { Database } from "@/server/db/types";

/**
 * Real Postgres (PGlite, in-process WASM) with the production migrations applied —
 * tests exercise actual SQL, constraints and transactions without Docker.
 */
export async function createTestDb(): Promise<{ db: Database; close: () => Promise<void> }> {
  const client = new PGlite();
  const db = drizzle(client, { schema });
  await migrate(db, { migrationsFolder: "./drizzle" });
  return { db: db as unknown as Database, close: () => client.close() };
}
