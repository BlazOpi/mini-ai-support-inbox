import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/** Git may check files out with Windows line endings; the output must be the same on every machine. */
const read = (path: string) => readFileSync(path, "utf8").replace(/\r\n/g, "\n");

/**
 * Builds `supabase/setup.sql`: all migrations plus the demo data in one file to paste into the
 * Supabase SQL Editor. The migrations stay the single source of truth, so this file can't describe
 * a different database than `npm run db:migrate` creates (a test fails if it wasn't rebuilt).
 */
export function buildSupabaseSetupSql(root = process.cwd()): string {
  const journal = JSON.parse(read(join(root, "drizzle/meta/_journal.json"))) as {
    entries: { tag: string; when: number }[];
  };
  const migrations = journal.entries.map((entry) => ({
    ...entry,
    sql: read(join(root, "drizzle", `${entry.tag}.sql`)),
  }));

  const statements = migrations
    .map((m) => `-- Migration ${m.tag}\n${m.sql.replaceAll("--> statement-breakpoint", "").trim()}`)
    .join("\n\n");
  const applied = migrations
    .map((m) => `  ('${createHash("sha256").update(m.sql).digest("hex")}', ${m.when})`)
    .join(",\n");

  return `-- Mini AI Support Inbox: everything a new Supabase project needs, in one file.
-- Supabase dashboard > SQL Editor > paste this whole file > Run.
-- It creates the tables, turns on Row Level Security and loads the demo tickets.
-- It all runs in one transaction, so if anything fails, nothing is changed.
--
-- GENERATED by \`npm run db:supabase-sql\` from drizzle/*.sql and supabase/seed.sql. Don't edit it by hand.

begin;

-- Stop with a clear message instead of a confusing "already exists" error on a second run.
do $$
begin
  if to_regclass('public.messages') is not null then
    raise exception 'The inbox tables already exist, so nothing was changed. For demo data only, run supabase/seed.sql.';
  end if;
end $$;

${statements}

-- Tells \`npm run db:migrate\` that these migrations are done, so it only runs newer ones later.
create schema if not exists drizzle;
create table if not exists drizzle.__drizzle_migrations (
  id serial primary key,
  hash text not null,
  created_at bigint
);
insert into drizzle.__drizzle_migrations (hash, created_at) values
${applied};

-- Demo data (supabase/seed.sql)
${read(join(root, "supabase/seed.sql")).trim()}

commit;
`;
}
